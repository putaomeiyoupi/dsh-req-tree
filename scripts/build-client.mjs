#!/usr/bin/env node
/**
 * Wraps the hand-written client source into the bundle shape the DSH client
 * module loader expects.
 *
 * The loader calls `factory(require)` with only *bare* specifiers it can
 * satisfy from its own registry (`react`, `react/jsx-runtime`, host packages).
 * A relative import like `./client.js` would reach for a filesystem path the
 * browser has no idea about, so the shipped bundle must be self-contained: the
 * source is inlined and `export`/`import` statements rewritten to CommonJS on
 * `module.exports`. That is the whole reason this script exists — the panel
 * source itself stays readable ESM.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const libDir = join(root, 'lib');
const packageName = JSON.parse(await readFile(join(root, 'package.json'), 'utf8')).name;

const source = await readFile(join(libDir, 'client.js'), 'utf8');

// `export function`/`export const` -> plain declarations on `module.exports`.
let body = source.replace(/^export (const|function|class|async function)\s/gm, '$1 ');
body = body.replace(/^export\s+\{[^}]*\}\s*(from\s*['"][^'"]*['"])?\s*;?\s*$/gm, '');

// Rewrite the remaining bare imports into `require` calls, preserving order.
const requires = [];
body = body.replace(/^import\s+(.+?)\s+from\s+['"]([^'"]+)['"];?\s*$/gm, (_match, clause, specifier) => {
  requires.push(specifier);
  const spec = JSON.stringify(specifier);
  const namespaceMatch = clause.match(/^\*?\s*as\s+(\w+)\s*$/);
  if (namespaceMatch !== null) return `const ${namespaceMatch[1]} = require(${spec});`;
  const names = clause.match(/^\s*\{([^}]*)\}\s*$/);
  if (names !== null) {
    // `{ jsx as _jsx }` binds the `jsx` export to the name `_jsx`; in a
    // destructuring pattern that spelling is `jsx: _jsx`.
    const fields = names[1]
      .split(',')
      .map((part) => part.trim())
      .filter(Boolean)
      .map((part) => part.split(/\s+as\s+/))
      .map(([original, alias]) => (alias === undefined ? original : `${original}: ${alias}`));
    return `const { ${fields.join(', ')} } = require(${spec});`;
  }
  const defaultMatch = clause.match(/^\s*(\w+)\s+as\s+(\w+)\s*$/);
  if (defaultMatch !== null) return `const ${defaultMatch[2]} = require(${spec}).default;`;
  return `require(${spec});`;
});

if (/^\s*import\s/m.test(body) || /^\s*export\s/m.test(body)) {
  throw new Error('client source still contains import/export after rewriting — the bundle would not load');
}

const header = `// Generated by scripts/build-client.mjs. Edit lib/client.js instead.
// Plugin-owned styles are inlined on purpose: the panel must not depend on
// generated design-export names or on host CSS module hashes.
window.__ModuleLoader__.load({
	id: ${JSON.stringify(packageName)},
	factory: (require) => {
		var module = { exports: {} };
		var exports = module.exports;
		Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
`;

const exportedNames = ['apply', 'inject', 'ReqTreeTab', 'LOCALE_NAMESPACE', 'TAB_ID', 'TAB_KIND', 'selectView', 'en', 'zh']
  .filter((name) => new RegExp(`^(?:const|function|async function|class)\\s+${name}\\b`, 'm').test(body));

const footer = `
		${exportedNames.map((name) => `exports.${name} = ${name};`).join('\n\t\t')}
		return module.exports;
	}
});
`;

const output = `${header}\n${body.trimEnd()}\n${footer}`;

// Parse the emitted file with the same parser the browser will use. A rewrite
// bug must fail the build here, not as a blank tab at runtime.
try {
  new vm.Script(output, { filename: 'client.bundle.js' });
} catch (error) {
  throw new Error(`generated bundle does not parse: ${error instanceof Error ? error.message : String(error)}`);
}

await writeFile(join(libDir, 'client.bundle.js'), output, 'utf8');
console.log(`wrote lib/client.bundle.js (${requires.length} require(s): ${requires.join(', ')})`);